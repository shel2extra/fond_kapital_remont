async def download_and_save(session, link_download, name_file, name_folder):
    try:
        async with session.get(link_download, headers=headers.generate()) as response:
            total_size = int(response.headers.get('content-length', 0))
            tqdm_params = {
                'desc': name_file,
                'total': total_size,
                'miniters': 1,
                'unit': 'it',
                'unit_scale': True,
                'leave': None,
                'position': 0,
                'unit_divisor': 1024,
            }

            with tqdm(**tqdm_params) as pb, open(f'{name_folder}/{name_file}', 'wb') as f:
                async for chunk in response.content.iter_any():
                    pb.update(len(chunk))
                    f.write(chunk)
    except:
        pass


